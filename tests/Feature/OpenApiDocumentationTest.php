<?php

declare(strict_types=1);

use Illuminate\Foundation\Testing\RefreshDatabase;
use function Pest\Laravel\getJson;

uses(RefreshDatabase::class);

it('generates openapi swagger documentation containing registered endpoints and schemas', function () {
    $response = getJson('/docs/api.json');

    $response->assertOk()
        ->assertJsonStructure([
            'openapi',
            'info' => ['title', 'version'],
            'paths',
            'components' => ['schemas'],
        ]);

    $paths = $response->json('paths');

    // Only the /checkout endpoint is exposed (zombie endpoints cleaned up)
    expect(array_keys($paths))->toEqual(['/checkout'])
        ->and($paths['/checkout'])->toHaveKey('post');

    $checkoutPost = $paths['/checkout']['post'];

    // Validates documented HTTP response status codes generated by Scramble
    expect($checkoutPost['responses'])->toHaveKeys(['201', '422'])
        ->and($checkoutPost)->toHaveKey('requestBody');

    // Validates request schema ref and component definition
    expect($checkoutPost['requestBody']['content']['application/json']['schema'])->toHaveKey('$ref');

    $components = $response->json('components.schemas');
    expect($components)->toHaveKey('CheckoutRequest');

    $checkoutRequestSchema = $components['CheckoutRequest'];
    expect($checkoutRequestSchema['properties'])->toHaveKeys([
        'checkout_token',
        'items',
        'coupon_code',
        'customer_email',
        'currency',
        'return_url',
        'cancel_url',
    ]);
});
